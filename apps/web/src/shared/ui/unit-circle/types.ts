/**
 * Декларативное описание единичной окружности для отбора корней
 * тригонометрических уравнений (задание 13, пункт «б»).
 *
 * Углы задаются в градусах, 0° — направление вправо (ось x),
 * отсчёт против часовой стрелки (как на тригонометрическом круге).
 */

export type CirclePointKind =
  /** Корень уравнения — закрашенная точка бренда. */
  | "root"
  /** Выколотая точка (ОДЗ / знаменатель) — светлый кружок с обводкой. */
  | "hole"
  /** Отобранный корень (ответ) — крупная тёмная точка. */
  | "selected"
  /** Вспомогательная маленькая точка. */
  | "plain";

export type CirclePoint = {
  /** Угол в градусах (0° вправо, против часовой стрелки). */
  angle: number;
  /** Подпись у точки. Дробь вида «5π/6» рендерится столбиком. */
  label?: string;
  kind?: CirclePointKind;
  /** Радиальный сдвиг подписи наружу как доля радиуса (по умолчанию 0.36). */
  labelGap?: number;
};

export type CircleArc = {
  /** Начало дуги, градусы. */
  from: number;
  /** Конец дуги, градусы. Дуга идёт против часовой стрелки от from к to. */
  to: number;
};

export type AxisLabels = {
  right?: string;
  top?: string;
  left?: string;
  bottom?: string;
};

export type UnitCircleSpec = {
  points?: CirclePoint[];
  /** Выделенные дуги — интервал отбора. */
  arcs?: CircleArc[];
  /** Подписи концов осей (значения углов для выбранной ветви). */
  axisLabels?: AxisLabels;
  /** Радиус окружности в пикселях (по умолчанию 116). */
  radius?: number;
  caption?: string;
};
